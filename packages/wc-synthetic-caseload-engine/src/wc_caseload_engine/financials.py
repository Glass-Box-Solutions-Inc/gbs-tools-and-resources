def financial_manifest_block(facts: FinancialFacts) -> dict[str, Any]:
    """Serialize configured domains with exact money strings and authority flags."""
    block: dict[str, Any] = {}
    if facts.rating is not None:
        rating = facts.rating
        block["rating"] = {
            "wpi": rating.wpi,
            "pdPercent": rating.pd_percent,
            "method": rating.method,
            "authority": rating.authority,
            "counselConfirmed": rating.counsel_confirmed,
            "source": rating.source,
        }
    if facts.reserves is not None:
        block["reserves"] = {
            "entries": [
                {
                    "eventDate": entry.event_date.isoformat(),
                    "reason": entry.reason,
                    "medical": _dollars(entry.medical),
                    "indemnity": _dollars(entry.indemnity),
                    "expense": _dollars(entry.expense),
                    "total": _dollars(entry.total),
                    "source": entry.source,
                }
                for entry in facts.reserves.entries
            ]
        }
    if facts.disbursement is not None:
        ledger = facts.disbursement
        block["disbursement"] = {
            "grossAmount": _dollars(ledger.gross_amount),
            "items": [
                {
                    "payee": item.payee,
                    "category": item.category,
                    "amount": _dollars(item.amount),
                    "paidDate": item.paid_date.isoformat() if item.paid_date else None,
                    "reference": item.reference,
                }
                for item in ledger.items
            ],
            "totalDisbursed": _dollars(ledger.total_disbursed),
            "applicantNet": _dollars(ledger.applicant_net),
            "reconciled": ledger.reconciled,
        }
    if facts.billing is not None:
        ledger = facts.billing
        block["billing"] = {
            "lines": [
                {
                    "invoiceId": line.invoice_id,
                    "provider": line.provider,
                    "serviceDate": line.service_date.isoformat(),
                    "charge": _dollars(line.charge),
                    "paid": _dollars(line.paid),
                    "adjustment": _dollars(line.adjustment),
                    "outstanding": _dollars(line.outstanding),
                    "lienAmount": _dollars(line.lien_amount),
                    "cptCodes": list(line.cpt_codes),
                }
                for line in ledger.lines
            ],
            "totals": {
                "charged": _dollars(ledger.total_charged),
                "paid": _dollars(ledger.total_paid),
                "adjusted": _dollars(ledger.total_adjusted),
                "outstanding": _dollars(ledger.total_outstanding),
                "liens": _dollars(ledger.total_liens),
            },
        }
    if facts.penalties is not None:
        ledger = facts.penalties
        block["penalties"] = {
            "exposures": [
                {
                    "source": item.source,
                    "principal": _dollars(item.principal),
                    "daysLate": item.days_late,
                    "rate": f"{item.rate.normalize():f}",
                    "amount": _dollars(item.amount),
                    "authority": item.authority,
                    "counselConfirmed": item.counsel_confirmed,
                    "assessedDate": (
                        item.assessed_date.isoformat() if item.assessed_date else None
                    ),
                }
                for item in ledger.exposures
            ],
            "totalExposure": _dollars(ledger.total_exposure),
        }
    return block


