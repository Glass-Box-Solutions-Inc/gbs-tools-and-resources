"""What every digest in a golden has to look like."""


def _demo_manifest_paths(demo_caseload: Path) -> list[Path]:
    """Every case manifest of the shared demo caseload."""
    return sorted(demo_caseload.glob("*/manifest.json"))


def _write_json(path: Path, payload: Any) -> Path:
    """Write *payload* the way the engine writes a manifest."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(canonical_json_bytes(payload))
    return path


def _build_corpus(root: Path, documents: tuple[str, ...] = ("001.pdf", "002.pdf")) -> Path:
    """A minimal but structurally real output tree, with no substrate needed.

    Everything the byte-level probes need and nothing they do not: one case,
    a manifest declaring its documents, the two per-case artifacts, and files
    on disk. Built by hand rather than generated so a probe can corrupt exactly
    one thing and leave the rest correct — which is what makes the result a
    statement about that one thing.
    """
    root.mkdir(parents=True, exist_ok=True)
    provenance = {
        "zeroRealPii": True,
        "generator": "wc-synthetic-caseload-engine@0.9.0",
        "substrateSha": "a" * 40,
    }
    _write_json(
        root / "caseload_manifest.json",
        {"caseloadId": "probe", "generator": "wc@0.9.0", "provenance": dict(provenance)},
    )
    case = root / "case-a"
    (case / "documents").mkdir(parents=True, exist_ok=True)
    for index, name in enumerate(documents):
        (case / "documents" / name).write_bytes(f"body of {name}".encode())
        del index
    _write_json(
        case / "manifest.json",
        {
            "caseId": "case-a",
            "documents": [
                {"filename": name, "subtype": "MEDICAL_REPORT", "md5Checksum": f"{index:032d}"}
                for index, name in enumerate(documents)
            ],
            "provenance": dict(provenance),
        },
    )
    (case / "seed.yaml").write_text("case_id: case-a\n", encoding="utf-8")
    (case / "case_facts.yaml").write_text("surgery:\n  status: none\n", encoding="utf-8")
    return root


