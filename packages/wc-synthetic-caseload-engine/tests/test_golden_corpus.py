def test_the_tree_digest_ignores_substrate_sha_and_nothing_else(tmp_path: Path) -> None:
    """The exemption applies through the tree digest too, and stops there."""
    root = _build_corpus(tmp_path / "corpus")
    baseline = digest_corpus(root)

    manifest_path = root / "case-a" / "manifest.json"
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    payload["provenance"]["substrateSha"] = "f" * 40
    _write_json(manifest_path, payload)
    assert digest_corpus(root)["corpusTree"] == baseline["corpusTree"], (
        "substrateSha is checkout-dependent and must not read as corpus drift"
    )

    payload["provenance"]["generator"] = "wc-synthetic-caseload-engine@99.0.0"
    _write_json(manifest_path, payload)
    assert digest_corpus(root)["corpusTree"] != baseline["corpusTree"], (
        "a version bump changes shipped bytes and must redden the gate"
    )


