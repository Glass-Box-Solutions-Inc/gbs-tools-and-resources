def test_a_failure_midway_through_writing_rolls_every_golden_back(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The generation phase is atomic; so is the write phase.

    Proving all the corpora reproducible before writing any of them closes the
    big window, and leaves a small one: the writes themselves. A full disk, a
    permissions change or a Ctrl-C between the first file and the second leaves
    exactly the incoherent set the design argues against, and no amount of
    care in the phase before it helps.

    The probe fails the *second* of two replacements, which is the only
    arrangement that can tell a real rollback from a lucky ordering: the first
    file has genuinely been replaced by the time the failure lands, so it can
    only be byte-identical again if something put it back.
    """
    goldens = {"first": tmp_path / "first.json", "second": tmp_path / "second.json"}
    for path in goldens.values():
        path.write_text('{"format": 1, "sentinel": "original"}\n', encoding="utf-8")
    before = {name: path.read_bytes() for name, path in goldens.items()}
    monkeypatch.setattr(Corpus, "golden", property(lambda self: goldens[self.name]))
    monkeypatch.setattr(
        golden_gate, "generate_corpus", lambda _corpus, out_dir: _build_corpus(out_dir)
    )
    monkeypatch.setattr(golden_gate, "validate_corpus", lambda *_args: None)

    real_replace = golden_gate.os.replace
    calls = {"n": 0}

    def _failing_replace(source: Any, destination: Any) -> None:
        calls["n"] += 1
        if calls["n"] == 2:
            raise OSError(28, "No space left on device", str(destination))
        return real_replace(source, destination)

    monkeypatch.setattr(golden_gate.os, "replace", _failing_replace)

    corpora = [
        Corpus(name="first", tier=SUITE_TIER, why="probe"),
        Corpus(name="second", tier=SUITE_TIER, why="probe"),
    ]
    assert golden_gate.record(corpora) == 1
    # At least the two commits; the rollback restores through os.replace as well.
    assert calls["n"] >= 2, "the probe never reached the second replacement"
    for name, path in goldens.items():
        assert path.read_bytes() == before[name], (
            f"{name}.json was left rewritten after the record run failed"
        )
    assert not list(tmp_path.glob(".*")), "a staged temporary was left behind"


def _two_corpus_record_fixture(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> tuple[list[Corpus], dict[str, Path], dict[str, bytes]]:
    """Two recordable corpora with committed goldens, and their original bytes."""
    goldens = {"first": tmp_path / "first.json", "second": tmp_path / "second.json"}
    for path in goldens.values():
        path.write_text('{"format": 1, "sentinel": "original"}\n', encoding="utf-8")
    before = {name: path.read_bytes() for name, path in goldens.items()}
    monkeypatch.setattr(Corpus, "golden", property(lambda self: goldens[self.name]))
    monkeypatch.setattr(
        golden_gate, "generate_corpus", lambda _corpus, out_dir: _build_corpus(out_dir)
    )
    monkeypatch.setattr(golden_gate, "validate_corpus", lambda *_args: None)
    corpora = [
        Corpus(name="first", tier=SUITE_TIER, why="probe"),
        Corpus(name="second", tier=SUITE_TIER, why="probe"),
    ]
    return corpora, goldens, before


def _replace_failing_on(
    calls: dict[str, int],
    failures: dict[int, BaseException],
    perform_first: frozenset[int] = frozenset(),
) -> Any:
    """An ``os.replace`` that raises on the numbered calls in *failures*.

    A call listed in *perform_first* does the real replacement and *then*
    raises, which is how an interrupt arriving between a successful replace and
    the next instruction is reproduced. That distinction is the whole content of
    the pre-tracking probe below: a failure before the replace and a failure
    after it leave the filesystem in two different states.
    """
    real_replace = golden_gate.os.replace

    def _replace(source: Any, destination: Any) -> None:
        calls["n"] += 1
        failure = failures.get(calls["n"])
        if failure is not None:
            if calls["n"] in perform_first:
                real_replace(source, destination)
            raise failure
        return real_replace(source, destination)

    return _replace


def test_an_interrupt_midway_through_writing_rolls_back_and_still_stops_the_program(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Ctrl-C is the interruption this function most needs to survive.

    An earlier version caught ``OSError`` and promised Ctrl-C recovery in its
    own docstring. ``KeyboardInterrupt`` inherits from ``BaseException``, not
    ``Exception``, so it matched nothing: an interrupt after the first
    replacement skipped the staged-file cleanup *and* the rollback, and left
    exactly the half-updated set the docstring said it prevented. The handler
    documenting a guarantee it does not implement is worse than no guarantee,
    because it is the reason nobody checks.

    Both halves are asserted, because either alone is satisfiable by a wrong
    implementation: the tree must come back, **and** the interrupt must still
    stop the program. Swallowing a Ctrl-C to tidy up is its own defect.
    """
    corpora, goldens, before = _two_corpus_record_fixture(tmp_path, monkeypatch)
    calls = {"n": 0}
    monkeypatch.setattr(
        golden_gate.os,
        "replace",
        _replace_failing_on(calls, {2: KeyboardInterrupt()}),
    )

    with pytest.raises(KeyboardInterrupt):
        golden_gate.record(corpora)

    # At least the two commits; the rollback restores through os.replace as well.
    assert calls["n"] >= 2, "the probe never reached the second replacement"
    for name, path in goldens.items():
        assert path.read_bytes() == before[name], (
            f"{name}.json was left rewritten after the run was interrupted"
        )
    assert not list(tmp_path.glob(".*")), "a staged temporary was left behind"


def test_a_replacement_that_succeeded_before_the_interrupt_is_still_rolled_back(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The window between a successful replace and the record of it.

    ``os.replace`` returning is not the same instant as the bookkeeping that
    says it returned, and an interrupt can be delivered in between. A list
    appended to *after* the call would not know that file had changed, so the
    rollback would skip it and leave exactly one golden updated — the failure
    this entire function exists to prevent, reached through a gap of one
    bytecode instruction.

    The probe performs the real replacement and *then* raises, which is the only
    way to tell pre-tracking from post-tracking: under post-tracking the second
    file is genuinely rewritten and stays that way.
    """
    corpora, goldens, before = _two_corpus_record_fixture(tmp_path, monkeypatch)
    calls = {"n": 0}
    monkeypatch.setattr(
        golden_gate.os,
        "replace",
        _replace_failing_on(calls, {2: KeyboardInterrupt()}, perform_first=frozenset({2})),
    )

    with pytest.raises(KeyboardInterrupt):
        golden_gate.record(corpora)

    for name, path in goldens.items():
        assert path.read_bytes() == before[name], (
            f"{name}.json was replaced before the interrupt and never rolled back"
        )
    assert not list(tmp_path.glob(".*")), "a staged temporary was left behind"


