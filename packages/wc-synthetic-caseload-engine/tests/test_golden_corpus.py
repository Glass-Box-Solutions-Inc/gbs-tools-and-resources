def test_exactly_one_field_is_exempt_from_the_digest() -> None:
    """The redaction list is the one thing here that can only weaken the gate.

    Every name in it is a field the gate stops watching, and the cost is
    invisible: it keeps reporting clean, just about less. Pinning the set means
    widening it is a decision somebody has to argue for in a diff rather than a
    line that slips through review.

    ``substrateSha`` earns its place by describing the *checkout* rather than
    the corpus — it disagrees with ``substrate_pin.txt`` in a clean tree — so
    digesting it would fail every commit for a reason unrelated to the bytes.
    """
    assert frozenset({"substrateSha"}) == REDACTED_KEYS
    for redactions in (
        golden_gate.CASE_REDACTIONS,
        golden_gate.CASELOAD_REDACTIONS,
    ):
        for path in redactions:
            assert path[-1] in REDACTED_KEYS, f"{path} redacts a field not in REDACTED_KEYS"


