REDACTED = "<redacted-for-golden>"
"""Stand-in written over a volatile field before a manifest is digested."""

REDACTED_KEYS: frozenset[str] = frozenset({"substrateSha"})
"""The **only** field name any digest is allowed to ignore.

Pinned as a set, and asserted to be exactly this, because a redaction list is
the one part of a checksum gate that weakens it. Every name added here is a
field the gate stops watching, and the cost of that is invisible: the gate keeps
reporting clean, just about less. ``test_golden_corpus.py`` fails if this set
ever grows, so widening it is a decision somebody has to argue for in a diff.

``generator`` was briefly in here and is deliberately not any more — see the
module docstring on the byte-identity contract.
"""

CASE_REDACTIONS: tuple[tuple[str, ...], ...] = (("provenance", "substrateSha"),)
"""Paths redacted from a case manifest before digesting. See the module docstring."""

CASELOAD_REDACTIONS: tuple[tuple[str, ...], ...] = (("provenance", "substrateSha"),)
"""Paths redacted from the caseload manifest before digesting."""

GOLDEN_FORMAT = 2
"""Golden manifest format version.

Bumped when the *shape* of a golden changes — a new per-case axis, a renamed
key. ``--check`` refuses a golden it was not built to read rather than comparing
half of it, because a partial comparison that reports clean is the one failure
mode a gate may never have.

Format 2 added ``corpusTree``/``tree``/``fileCount`` — the digests taken from
the files themselves rather than from the manifest's account of them — and
stopped exempting the engine version. Format 1 goldens are refused rather than
half-read: they record no byte-level digest at all, so comparing what they *do*
carry would report clean while checking strictly less than the gate claims.
"""


class GoldenError(RuntimeError):
    """A condition that makes a verdict impossible, as opposed to negative."""


