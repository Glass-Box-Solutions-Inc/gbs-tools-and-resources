def _run_cli(arguments: list[str]) -> subprocess.CompletedProcess[str]:
    """Run the shipped CLI as a subprocess of this interpreter.

    The environment is passed through deliberately untouched — see the module
    docstring on why ``PYTHONHASHSEED`` is left for the CLI's own re-exec.
    """
    return subprocess.run(
        [sys.executable, "-m", "wc_caseload_engine.cli", *arguments],
        capture_output=True,
        text=True,
        check=False,
        cwd=str(PACKAGE),
    )


def generate_corpus(corpus: Corpus, out_dir: Path) -> None:
    """Generate *corpus* into *out_dir* through the CLI, or raise."""
    if not corpus.spec.is_file():
        raise GoldenError(f"{corpus.name}: spec {corpus.spec} is not on disk")
    completed = _run_cli(
        ["generate", "--spec", str(corpus.spec), "--out", str(out_dir)]
    )
    if completed.returncode != 0:
        raise GoldenError(
            f"{corpus.name}: generation failed (exit {completed.returncode})\n"
            f"{completed.stdout[-2000:]}\n{completed.stderr[-2000:]}"
        )


def validate_corpus(corpus: Corpus, out_dir: Path) -> None:
    """Run ``validate --out`` over a generated corpus, or raise.

    Both ``--record`` and ``--check`` run this, for two different reasons.

    On record it refuses to bless a tree whose checksums or taxonomy are already
    wrong: a golden is a claim that this output is the *correct* output, and
    recording one from a broken tree pins the defect in place and calls it the
    baseline.

    On check it is the cross-examination of the manifest. The digests prove the
    corpus is the same as last time; ``validate`` proves the manifest still
    describes the files beside it — every declared MD5 re-hashed from disk,
    every subtype still classifier vocabulary, no document rendered by a
    fallback template. A corpus can be perfectly *stable* and still be wrong,
    and a gate that only checked stability would certify it.
    """
    completed = _run_cli(["validate", "--out", str(out_dir)])
    if completed.returncode != 0:
        raise GoldenError(
            f"{corpus.name}: the generated corpus does not validate (exit "
            f"{completed.returncode})\n{completed.stdout[-2000:]}\n{completed.stderr[-2000:]}"
        )


