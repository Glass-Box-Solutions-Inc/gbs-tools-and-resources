def _golden_bytes(
    corpus: Corpus, digest: dict[str, Any], provenance: dict[str, Any]
) -> bytes:
    """Serialize one golden. Pure — it touches no file."""
    payload = {
        "format": GOLDEN_FORMAT,
        "corpus": corpus.name,
        "spec": corpus.spec.relative_to(PACKAGE).as_posix(),
        "tier": corpus.tier,
        "recordedWith": provenance,
        **digest,
    }
    return (json.dumps(payload, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _commit_goldens(payloads: list[tuple[Corpus, bytes]]) -> None:
    """Write every golden, or leave every one of them exactly as it was.

    The generation phase is already all-or-nothing — nothing is written until
    every selected corpus has been generated twice and proved reproducible. This
    closes the remaining window: the *writes themselves*. Half a dozen
    sequential ``write_text`` calls can still be interrupted between the second
    and the third by a full disk, a permissions change, or a Ctrl-C, and what it
    leaves behind is precisely the incoherent set this command documents against
    — some goldens describing the new code, some the old, and a ``git status``
    that looks like a deliberate subset.

    Two mechanisms, because either alone leaves a hole:

    * Each file is written to a temporary beside its destination and moved into
      place with :func:`os.replace`, which is atomic within a filesystem. A
      reader never sees a half-written golden.
    * The previous contents are held in memory and restored if any replacement
      fails, so a failure on the third file un-does the first two.

    The rollback is best-effort and never masks the original error: if restoring
    also fails, the first failure is still what propagates, because that is the
    one that explains what happened.
    """
    GOLDEN_DIR.mkdir(parents=True, exist_ok=True)
    originals: dict[Path, bytes | None] = {
        corpus.golden: (corpus.golden.read_bytes() if corpus.golden.is_file() else None)
        for corpus, _payload in payloads
    }
    committed: list[Path] = []
    staged_paths: list[Path] = []
    try:
        for corpus, payload in payloads:
            destination = corpus.golden
            # Beside the destination, so os.replace stays within one filesystem.
            staged = destination.with_name(f".{destination.name}.staged")
            staged_paths.append(staged)
            staged.write_bytes(payload)
            os.replace(staged, destination)
            committed.append(destination)
    except OSError as exc:
        # A replace that failed leaves its own staged file behind. Cleaning up
        # matters more than it looks: the name is dotted, so it is invisible to
        # a casual `ls` and to `git status`, and a leftover would sit in
        # tests/golden/ indefinitely with nothing to say where it came from.
        for staged in staged_paths:
            with contextlib.suppress(OSError):  # cleanup's own failure is not the story
                staged.unlink(missing_ok=True)
        for path in committed:
            original = originals[path]
            with contextlib.suppress(OSError):  # the rollback's own failure is not the story
                if original is None:
                    path.unlink(missing_ok=True)
                else:
                    path.write_bytes(original)
        raise GoldenError(
            f"writing the goldens failed at {getattr(exc, 'filename', '<unknown>')} — "
            f"{exc}. The goldens written before it were rolled back, so the committed "
            "set is unchanged and still coherent."
        ) from exc


def _load_golden(corpus: Corpus) -> dict[str, Any]:
    """Read a committed golden, or explain how to create it."""
    if not corpus.golden.is_file():
        raise GoldenError(
            f"{corpus.name}: no golden at {corpus.golden.relative_to(PACKAGE)}. "
            f"Record one:\n    python tools/golden_gate.py --record --only {corpus.name}"
        )
    payload = json.loads(corpus.golden.read_text(encoding="utf-8"))
    if payload.get("format") != GOLDEN_FORMAT:
        raise GoldenError(
            f"{corpus.name}: golden is format {payload.get('format')!r}, this tool "
            f"reads format {GOLDEN_FORMAT}. Re-record it:\n"
            f"    python tools/golden_gate.py --record --only {corpus.name}"
        )
    return payload


def compare(corpus: Corpus, golden: dict[str, Any], fresh: dict[str, Any]) -> list[str]:
    """Every way *fresh* differs from *golden*, as report lines."""
    problems: list[str] = []

    for key, label in (
        ("caseCount", "case count"),
        ("documentCount", "document count"),
        ("fileCount", "file count"),
    ):
        if golden.get(key) != fresh.get(key):
            problems.append(f"{label}: {golden.get(key)} recorded, {fresh.get(key)} now")

    if golden.get("corpusTree") != fresh.get("corpusTree"):
        problems.append(
            f"corpus file bytes drifted "
            f"({_short(golden.get('corpusTree'))} -> {_short(fresh.get('corpusTree'))})"
        )

    if golden.get("caseload") != fresh.get("caseload"):
        problems.append(
            f"{CASELOAD_MANIFEST_NAME}: digest changed "
            f"({_short(golden.get('caseload'))} -> {_short(fresh.get('caseload'))})"
        )

    golden_cases: dict[str, Any] = golden.get("cases") or {}
    fresh_cases: dict[str, Any] = fresh.get("cases") or {}

    for missing in sorted(set(golden_cases) - set(fresh_cases)):
        problems.append(f"{missing}: recorded in the golden but this run did not produce it")
    for added in sorted(set(fresh_cases) - set(golden_cases)):
        problems.append(f"{added}: produced by this run but absent from the golden")

    for case_id in sorted(set(golden_cases) & set(fresh_cases)):
        was, now = golden_cases[case_id], fresh_cases[case_id]
        for key, label in (
            ("documentCount", "documents"),
            ("distinctSubtypes", "distinct subtypes"),
            ("fileCount", "files"),
        ):
            if was.get(key) != now.get(key):
                problems.append(
                    f"{case_id}: {label} {was.get(key)} recorded, {now.get(key)} now"
                )
        for axis, label in AXES:
            if was.get(axis) != now.get(axis):
                problems.append(
                    f"{case_id}: {label} drifted "
                    f"({_short(was.get(axis))} -> {_short(now.get(axis))})"
                )
    return problems


def _short(digest: Any) -> str:
    """First twelve hex characters — enough to tell two digests apart by eye."""
    return str(digest)[:12] if digest else "<absent>"


@dataclass(frozen=True, slots=True)
class Outcome:
    """What happened to one corpus."""

    corpus: Corpus
    problems: list[str]
    notes: list[str]
    kept: Path | None = None
    error: str | None = None

    @property
    def ok(self) -> bool:
        """``True`` when the corpus matched its golden and nothing blew up."""
        return not self.problems and self.error is None


def _selected(only: str | None, tier: str | None) -> list[Corpus]:
    """The corpora a run acts on, or raise on an unusable selection."""
    corpora = list(CORPORA)
    if only is not None:
        corpora = [corpus for corpus in corpora if corpus.name == only]
        if not corpora:
            known = ", ".join(corpus.name for corpus in CORPORA)
            raise GoldenError(f"unknown corpus {only!r}; known corpora are {known}")
    if tier is not None:
        corpora = [corpus for corpus in corpora if corpus.tier == tier]
        if not corpora:
            raise GoldenError(f"no corpus is in tier {tier!r}")
    return corpora


def _generate_twice(corpus: Corpus) -> dict[str, Any]:
    """Generate *corpus* twice in independent trees and require agreement.

    A golden is a promise that this output is reproducible. Recording one from a
    single run asserts that promise without ever testing it — and if the corpus
    had in fact become nondeterministic, that single run is exactly how the
    nondeterminism gets blessed as the baseline. Every subsequent ``--check``
    would then fail for a reason the golden itself caused, which is the worst
    outcome available: a gate manufacturing its own red.

    So the two runs are compared in full, and disagreement is a hard failure
    rather than a retry. Both are validated, because a run that does not
    validate is not evidence about anything.
    """
    digests: list[dict[str, Any]] = []
    for attempt in (1, 2):
        with tempfile.TemporaryDirectory(prefix=f"golden-{corpus.name}-{attempt}-") as scratch:
            out_dir = Path(scratch) / corpus.name
            generate_corpus(corpus, out_dir)
            validate_corpus(corpus, out_dir)
            digests.append(digest_corpus(out_dir))

    first, second = digests
    differences = compare(corpus, first, second)
    if differences:
        detail = "\n    ".join(differences[:10])
        raise GoldenError(
            f"{corpus.name}: two runs of this corpus disagree, so it is not reproducible "
            f"and must not be recorded as a golden. Recording it would pin the "
            f"nondeterminism as the baseline and make every later --check fail for a "
            f"reason this command caused.\n    {detail}"
        )
    return first


def record(corpora: list[Corpus]) -> int:
    """Regenerate each corpus twice and rewrite its golden. Returns an exit code.

    Transactional in both phases. Every selected corpus is generated, validated,
    proved reproducible and digested *before* any golden is written, and the
    writes themselves go through :func:`_commit_goldens`, which stages and
    rolls back. A partial record is the worst artifact this command could leave
    behind — half the goldens refreshed against new code, half still describing
    the old, and a ``git status`` that looks like a deliberate subset.
    """
    provenance = current_provenance()
    prepared: list[tuple[Corpus, dict[str, Any], dict[str, Any] | None]] = []

    for corpus in corpora:
        previous: dict[str, Any] | None = None
        if corpus.golden.is_file():
            previous = json.loads(corpus.golden.read_text(encoding="utf-8"))
        try:
            digest = _generate_twice(corpus)
        except GoldenError as exc:
            print(f"FAILED  {corpus.name}\n  {exc}")
            print("\nNo golden was written — --record is all-or-nothing.")
            return 1
        prepared.append((corpus, digest, previous))
        print(f"verified {corpus.name:<20} reproducible across two runs")

    try:
        _commit_goldens(
            [(corpus, _golden_bytes(corpus, digest, provenance)) for corpus, digest, _ in prepared]
        )
    except GoldenError as exc:
        print(f"FAILED  {exc}")
        return 1

    for corpus, digest, previous in prepared:
        changed = compare(corpus, previous, digest) if previous else []
        summary = (
            "new golden"
            if previous is None
            else (f"{len(changed)} change(s)" if changed else "unchanged")
        )
        print(
            f"RECORDED {corpus.name:<20} {digest['caseCount']} cases, "
            f"{digest['documentCount']} documents, {digest['fileCount']} files — {summary}"
        )
        for line in changed:
            print(f"    {line}")
    return 0


def check(corpora: list[Corpus], keep: Path | None) -> int:
    """Regenerate each corpus and compare with its golden. Returns an exit code."""
    provenance = current_provenance()
    outcomes: list[Outcome] = []

    for corpus in corpora:
        scratch = tempfile.mkdtemp(prefix=f"golden-{corpus.name}-")
        out_dir = Path(scratch) / corpus.name
        kept: Path | None = None
        try:
            try:
                golden = _load_golden(corpus)
                generate_corpus(corpus, out_dir)
                validate_corpus(corpus, out_dir)
                fresh = digest_corpus(out_dir)
            except GoldenError as exc:
                outcomes.append(Outcome(corpus, [], [], error=str(exc)))
                continue
            problems = compare(corpus, golden, fresh)
            notes = _provenance_notes(golden.get("recordedWith") or {}, provenance)
            if problems and keep is not None:
                kept = keep / corpus.name
                kept.parent.mkdir(parents=True, exist_ok=True)
                if kept.exists():
                    shutil.rmtree(kept)
                shutil.copytree(out_dir, kept)
            outcomes.append(Outcome(corpus, problems, notes, kept=kept))
        finally:
            shutil.rmtree(scratch, ignore_errors=True)

    return _report(outcomes)


def _report(outcomes: list[Outcome]) -> int:
    """Print the verdict for every corpus. Returns an exit code."""
    for outcome in outcomes:
        if outcome.error is not None:
            print(f"ERROR   {outcome.corpus.name}\n  {outcome.error}\n")
            continue
        if outcome.ok:
            print(f"OK      {outcome.corpus.name}")
            continue

        print("")
        print(f"GOLDEN DRIFT — {outcome.corpus.name}")
        print(f"  spec: {outcome.corpus.spec.relative_to(PACKAGE)}")
        if outcome.notes:
            print("")
            print("  This environment differs from the one that recorded the golden.")
            print("  None of these fails the gate on its own; one of them is usually why:")
            for note in outcome.notes:
                print(f"    {note}")
        print("")
        print(f"  {len(outcome.problems)} difference(s):")
        for problem in outcome.problems:
            print(f"    {problem}")
        if outcome.kept is not None:
            print("")
            print(f"  The regenerated corpus was kept at {outcome.kept}")
        print("")
        print("  If this change was intended, re-record the golden and commit the diff")
        print("  so a reviewer sees it:")
        print(f"    python tools/golden_gate.py --record --only {outcome.corpus.name}")
        print(f"    git add tests/golden/{outcome.corpus.name}.json")
        print("")

    drifted = [outcome.corpus.name for outcome in outcomes if not outcome.ok]
    if drifted:
        print(f"FAILED: {len(drifted)} of {len(outcomes)} corpora — {', '.join(drifted)}")
        return 1
    print(f"PASSED: {len(outcomes)} corpora byte-identical to their goldens")
    return 0


def list_corpora() -> int:
    """Print the registered corpora, their tier and whether a golden exists."""
    print(f"{'corpus':<20} {'tier':<6} {'golden':<9} why")
    for corpus in CORPORA:
        state = "recorded" if corpus.golden.is_file() else "MISSING"
        print(f"{corpus.name:<20} {corpus.tier:<6} {state:<9} {corpus.why}")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Entry point. Returns the process exit code."""
    parser = argparse.ArgumentParser(
        prog="golden_gate.py",
        description=(
            "Record and verify byte-level goldens for the shipped example corpora."
        ),
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--record",
        action="store_true",
        help="Regenerate the corpora and rewrite their goldens (commit the diff).",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="Regenerate the corpora and fail on any difference from the goldens.",
    )
    mode.add_argument("--list", action="store_true", help="List the registered corpora.")
    parser.add_argument("--only", metavar="CORPUS", help="Act on one corpus.")
    parser.add_argument(
        "--all",
        action="store_true",
        help="With --record, act on every corpus. Required: re-recording is never a default.",
    )
    parser.add_argument(
        "--tier",
        choices=(SUITE_TIER, CI_TIER),
        help=(
            f"Act only on corpora in this tier: {SUITE_TIER} is what the pytest gate "
            f"covers, {CI_TIER} what the dedicated CI step covers. Omit for all of them."
        ),
    )
    parser.add_argument(
        "--keep",
        type=Path,
        metavar="DIR",
        help="On drift, copy the regenerated corpus here for inspection.",
    )
    args = parser.parse_args(argv)

    if args.list:
        return list_corpora()

    try:
        corpora = _selected(args.only, args.tier)
    except GoldenError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if args.record:
        # Re-recording is how an intended change gets accepted, and a bare
        # `--record` is how an unintended one gets accepted by accident: it is
        # the fastest way to make a red gate green, it rewrites every corpus,
        # and the reviewer sees four changed files with no statement of intent.
        # Naming the scope is one word, and it is the word that says the
        # blessing was deliberate.
        if not (args.only or args.all or args.tier):
            print(
                "error: --record needs an explicit scope. Re-recording accepts new output "
                "as correct, so say what you meant to accept:\n"
                "    --only CORPUS   one corpus (the usual case)\n"
                "    --tier TIER     every corpus in a tier\n"
                "    --all           every corpus, deliberately",
                file=sys.stderr,
            )
            return 2
        return record(corpora)
    return check(corpora, args.keep)


if __name__ == "__main__":  # pragma: no cover - exercised as a subprocess
    os.environ.setdefault("PYTHONDONTWRITEBYTECODE", "1")
    sys.exit(main())
